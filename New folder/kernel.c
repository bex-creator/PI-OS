// ==========================================
// 3. GRAPHICS ENGINE & TEXT RENDERER
// ==========================================
int mbox_call(uint8_t ch) {
    uint32_t addr = (uint32_t)((uintptr_t)mbox & ~0xF) | (ch & 0xF);
    while (MBOX1_STATUS & MBOX_FULL);
    MBOX1_WRITE = addr;
    while (1) {
        while (MBOX0_STATUS & MBOX_EMPTY);
        if (MBOX0_READ == addr) return mbox[1] == MBOX_RESPONSE;
    }
}

void draw_pixel(uint32_t x, uint32_t y, uint32_t color) {
    if (x < screen_width && y < screen_height && framebuffer) {
        framebuffer[y * (screen_pitch / 4) + x] = color;
    }
}

void draw_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    for (uint32_t i = 0; i < h; i++) {
        for (uint32_t j = 0; j < w; j++) {
            draw_pixel(x + j, y + i, color);
        }
    }
}

// Draw a single character using the font engine
void draw_char(char c, uint32_t x, uint32_t y, uint32_t color, int scale) {
    if (c < 32 || c > 90) c = '?'; // Fallback for unsupported chars
    const uint8_t *glyph = &font8x8[(c - 32) * 8];

    for (int cy = 0; cy < 8; cy++) {
        for (int cx = 0; cx < 8; cx++) {
            if (glyph[cy] & (1 << (7 - cx))) {
                draw_rect(x + (cx * scale), y + (cy * scale), scale, scale, color);
            }
        }
    }
}

// Draw full string on screen
void draw_string(const char *str, uint32_t x, uint32_t y, uint32_t color, int scale) {
    while (*str) {
        draw_char(*str, x, y, color, scale);
        x += 8 * scale + 2; // Move cursor right
        str++;
    }
}

// Console Print Routine (`kprint`)
void kprint(const char *str, uint32_t color) {
    while (*str) {
        if (*str == '\n') {
            cursor_x = 40;
            cursor_y += 20;
        } else {
            draw_char(*str, cursor_x, cursor_y, color, 2);
            cursor_x += 18;
        }
        str++;
    }
}

void init_framebuffer(void) {
    mbox[0] = 35 * 4;
    mbox[1] = MBOX_REQUEST;
    mbox[2] = MBOX_TAG_SET_PHYS_WH; mbox[3] = 8; mbox[4] = 8; mbox[5] = 1024; mbox[6] = 768;
    mbox[7] = MBOX_TAG_SET_VIRT_WH; mbox[8] = 8; mbox[9] = 8; mbox[10] = 1024; mbox[11] = 768;
    mbox[12] = MBOX_TAG_SET_DEPTH;  mbox[13] = 4; mbox[14] = 4; mbox[15] = 32;
    mbox[16] = MBOX_TAG_ALLOC_BUF;  mbox[17] = 8; mbox[18] = 8; mbox[19] = 16; mbox[20] = 0;
    mbox[21] = MBOX_TAG_GET_PITCH;  mbox[22] = 4; mbox[23] = 4; mbox[24] = 0;
    mbox[25] = MBOX_TAG_LAST;

    if (mbox_call(8)) {
        framebuffer = (uint32_t *)(uintptr_t)(mbox[19] & 0x3FFFFFFF);
        screen_pitch = mbox[24];
    }
}

// Delay loop for OS timing
void delay(uint32_t count) {
    for (volatile uint32_t i = 0; i < count * 10000; i++);
}

// ==========================================
// 4. MAIN KERNEL ENTRY POINT
// ==========================================
void kernel_main(void) {
    init_framebuffer();

    if (framebuffer) {
        // Clear Desktop Background
        draw_rect(0, 0, 1024, 768, COLOR_BG);

        // Top OS Status Bar
        draw_rect(0, 0, 1024, 40, COLOR_PANEL);
        draw_rect(0, 38, 1024, 2, COLOR_HEADER);
        draw_string("NEXUS OS  v0.2  |  ARCH: ARM64 (AARCH64)  |  BOARD: RASPBERRY PI 5", 20, 12, COLOR_TEXT, 2);

        // System Console Panel
        draw_rect(20, 60, 984, 680, COLOR_PANEL);
        draw_rect(20, 60, 984, 30, COLOR_HEADER);
        draw_string("SYSTEM CONSOLE LOG", 30, 68, COLOR_TEXT, 2);

        // Print Kernel Initialization Logs
        kprint("BOOTING NEXUS KERNEL...\n", COLOR_GREEN);
        kprint("INITIALIZING GPU FRAMEBUFFER AT 1024X768...\n", COLOR_TEXT);
        kprint("FONT ENGINE LOADED [OK]\n", COLOR_GREEN);
        kprint("CPU CORE 0 INITIALIZED IN EL1 MODE\n", COLOR_TEXT);
        kprint("READY FOR COMMANDS.\n\n", COLOR_YELLOW);

        kprint("NEXUS SHELL > ", COLOR_HEADER);
    }

    // Live system heartbeat loop
    uint32_t pulse = 0;
    while (1) {
        delay(5000);
        pulse = !pulse;
        // Animated green cursor pulse at prompt location
        draw_rect(cursor_x, cursor_y, 14, 16, pulse ? COLOR_GREEN : COLOR_PANEL);
    }
}
